	/**
	 * Normalizes an icon name by removing the "dashicons-" prefix.
	 *
	 * @param string $icon Icon name.
	 */
	public static function normalize( string $icon ): string {
		return str_replace( 'dashicons-', '', strtolower( trim( $icon ) ) );
	}

	/**
	 * Tells whether the icon is a known Dashicon.
	 *
	 * @param string $icon Icon name, with or without prefix.
	 */
	public static function exists( string $icon ): bool {
		return in_array( self::normalize( $icon ), self::ICONS, true );
	}
